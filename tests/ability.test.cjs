// 能力文の分解ツール（tools/ability.mjs）の試験。ブラウザは使わない
const H = require('./harness.cjs');
const { ok } = H;
(async()=>{
  const A = await import(H.ROOT + '/tools/ability.mjs');
  const P = A.loadParts(H.ROOT + '/data/ability-parts.json');
  const rt = t => { const r = A.parse(t, P); return r.ok && A.render(r.ability, P) === t; };

  // 組み立て直すと印字と1文字も違わない
  ok(rt('このワザを使ったとき、カードを1枚引く。'), '「〜を〜たとき」の形を分解して組み立て直せる');
  ok(rt('このバトルに勝ったとき、自分はカードを1枚引く。'), '「〜に〜たとき」と「自分は」の形を分解して組み立て直せる');
  ok(rt('自分のホロビトが4体以上ラインに出ているなら、このホロビトのパワーを+4000する。'), '色の指定がない「自分のホロビトが4体以上」を分解できる');
  ok(rt('自分の赤のホロビトが4体以上ラインに出ているなら、このホロビトのパワーを+5000する。'), '色の指定がある形も同じ部品で分解できる');
  ok(!A.parse('このホロビトが出たとき、カードを1枚すてる。', P).ok, '辞書にない文面は分解しない（それらしく埋めない）');

  // 転記ゆれの検出から除く「正当な違い」
  const R = '自分の赤のホロビトが4体以上ラインに出ているなら、このホロビトのパワーを+5000する。';
  ok(A.sameShape(R, '自分のホロビトが4体以上ラインに出ているなら、このホロビトのパワーを+4000する。', P), '省略できる語の有無と数字だけの違いは正当とみなす');
  ok(A.sameShape('このホロビトが出たとき、カードを1枚引く。', 'このホロビトが出たとき、カードを2枚引く。', P), '数字だけの違いは正当とみなす');
  ok(!A.sameShape(R, '自分の青のホロビトが4体以上ラインに出ているなら、このホロビトのパワーを+5000する。', P), '同じ引数に違う文字（赤→青）は正当とみなさない（転記ミスの可能性として止める）');
  ok(!A.sameShape(R, '自分の赤のホロビトが4体以上ラインに出ているなら、そのホロビトのパワーを+5000する。', P), '引数の文字の違い（この→その）は正当とみなさない');
  await H.finish();
})();
